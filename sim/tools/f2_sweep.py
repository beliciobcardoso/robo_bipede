"""F2 design sweep: which thigh / shin lengths and hip width leave margin on the SG90?

    .venv/bin/python sim/tools/f2_sweep.py            # full grid, all CPU cores (~1 min)
    .venv/bin/python sim/tools/f2_sweep.py --quick    # small grid for a smoke check

Every grid point is a different robot (generated by build_biped.BipedParams), so the sweep runs
one model per CPU core rather than one batch on the GPU: each robot is simulated only a few
times and the whole grid takes about a minute. (The GPU pays off when the same robot runs
thousands of times: robustness tests, F7 training.)

Measures per robot:
  rise   (sim)       stand up from a 34° crouch in 0.6 s                 -> knee peak
  tilt   (sim)       one-leg stance: the stable tilt where the stance ankle roll works least
                     (weight right over the foot)                        -> tilt needed, stance torques
  shift  (physics)   moving the weight from between the feet onto one foot: the stance ankle roll
                     must rotate the whole robot about that foot. Peak torque ≈ m·g·(hip spacing/2)
                     + I·α, with I = m·(h² + (s/2)²) about the foot and α the peak angular
                     acceleration of a smooth tilt of `tilt needed` in 1/6 of the step cycle, at 0.5
                     and 1 step/s. Open-loop rocking in simulation is too sensitive to the motion
                     pattern to rank designs (see rocking_test.py); this estimate matched it within
                     ~10 points on the F1 robot.
Foot width = min(45 mm, hip spacing - 5 mm) so the feet never touch.
Pass criteria (docs/arquitetura_perna.md): every peak < 70 % of the SG90 and tilt needed < 20°.
"Robust" = also passes with heavy covers (2× cover mass).

Writes sim/results/f2_sweep.csv and sim/results/f2_sweep.png.
"""

import argparse
import csv
import itertools
import multiprocessing as mp
import sys
import time
from dataclasses import replace
from pathlib import Path

import mujoco
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_biped import BipedParams, build_xml  # noqa: E402
from f1_experiments import SG90, Robot, one_leg_scan, rise_peak  # noqa: E402

RESULTS = Path(__file__).resolve().parents[1] / "results"
LIMIT = 70.0                    # % of SG90
TILT_LIMIT = 20.0               # degrees
ROLL_SOFT_LIMIT_DEG = 25.0      # ankle roll software limit
STANCE_CROUCH = 0.2             # same stance crouch as the one-leg test
G = 9.81
FOOT_GAP_MM = 5.0              # free space between the two feet
FOOT_MAX_WIDTH_MM = 45.0       # widest foot tried (narrower when the hips are close)
COVERS = {"nominais": 1.0, "pesadas": 2.0}   # multiplier on the cover masses computed from their shape (body.py)
PACES = {"05": 4.0, "10": 2.0}  # step rate label -> cycle period (s)

GRID = dict(thigh=(35, 40, 45, 50, 55, 60), shin=(35, 40, 45, 50, 55, 60),
            hip_spacing=(40, 45, 50, 55, 60), covers=tuple(COVERS))
QUICK = dict(thigh=(40, 45, 55), shin=(40, 45, 55), hip_spacing=(45, 55), covers=("nominais",))


def pct(nm: float) -> float:
    return 100.0 * nm / SG90


def com_height(m: mujoco.MjModel) -> float:
    """Height of the centre of mass above the soles in the stance crouch (m)."""
    r = Robot(m)
    d = mujoco.MjData(m)
    u = r.ctrl({"l": STANCE_CROUCH, "r": STANCE_CROUCH})
    for i in r.idx.values():
        d.qpos[m.jnt_qposadr[m.actuator_trnid[i, 0]]] = u[i]
    mujoco.mj_kinematics(m, d)
    mujoco.mj_comPos(m, d)
    return float(d.subtree_com[1][2] - d.site_xpos[m.site("sole_l").id][2])


def shift_torque(mass_kg: float, h: float, half_spacing: float, tilt_rad: float, period: float) -> float:
    """Peak stance ankle-roll torque to move the weight onto one foot (N·m), see module doc."""
    t_shift = period / 6
    alpha = (np.pi ** 2 / 2) * tilt_rad / t_shift ** 2      # peak of a cosine-ramped tilt
    inertia = mass_kg * (h ** 2 + half_spacing ** 2)
    return mass_kg * G * half_spacing + inertia * alpha


def evaluate(point: tuple) -> dict:
    thigh, shin, spacing, covers = point
    base = BipedParams()
    fx, fy, fz = base.foot_size_mm
    foot_w = min(FOOT_MAX_WIDTH_MM, spacing - FOOT_GAP_MM)   # feet must not touch each other
    p = replace(base, thigh_mm=thigh, shin_mm=shin, hip_half_width_mm=spacing / 2,
                cover_scale=COVERS[covers], foot_size_mm=(fx, foot_w, fz))
    m = mujoco.MjModel.from_xml_string(build_xml(p))
    mass = float(m.body_subtreemass[1])
    row = dict(thigh_mm=thigh, shin_mm=shin, hip_spacing_mm=spacing, foot_width_mm=foot_w, covers=covers,
               mass_g=round(mass * 1000))

    rise, fell = rise_peak(m, speed=1.0)
    row.update(rise_knee_pct=pct(rise["knee"]), rise_fell=fell)

    scan = [s for s in one_leg_scan(m, phis_deg=np.arange(-ROLL_SOFT_LIMIT_DEG + 1, 7, 2)) if s[1]]
    if scan:
        best = min(scan, key=lambda s: s[3]["ankle_roll"])
        row.update(tilt_needed_deg=abs(best[0]), tilt_lo=min(s[0] for s in scan), tilt_hi=max(s[0] for s in scan),
                   stance_worst_pct=pct(max(best[3].values())))
    else:
        row.update(tilt_needed_deg=np.nan, tilt_lo=np.nan, tilt_hi=np.nan, stance_worst_pct=np.nan)

    h = com_height(m)
    row["com_height_mm"] = h * 1000
    tilt = np.radians(row["tilt_needed_deg"]) if scan else np.nan
    for label, period in PACES.items():
        row[f"shift{label}_pct"] = pct(shift_torque(mass, h, spacing / 2000, tilt, period))
    return _verdict(row)


def _verdict(row: dict) -> dict:
    base = (not row["rise_fell"] and row["rise_knee_pct"] < LIMIT
            and not np.isnan(row["tilt_needed_deg"]) and row["tilt_needed_deg"] < TILT_LIMIT
            and row["stance_worst_pct"] < LIMIT)
    row["pass_05"] = bool(base and row["shift05_pct"] < LIMIT)
    row["pass_10"] = bool(row["pass_05"] and row["shift10_pct"] < LIMIT)
    row["worst_pct_at_1step"] = float(max(row["rise_knee_pct"], row["shift10_pct"],
                                          row["stance_worst_pct"] if not np.isnan(row["stance_worst_pct"]) else 0))
    return row


def run_grid(grid: dict) -> list[dict]:
    points = list(itertools.product(grid["thigh"], grid["shin"], grid["hip_spacing"], grid["covers"]))
    t0 = time.time()
    with mp.Pool() as pool:
        rows = pool.map(evaluate, points, chunksize=1)
    print(f"{len(points)} robôs simulados em {time.time() - t0:.0f} s ({mp.cpu_count()} núcleos)\n")
    return rows


def save_csv(rows: list[dict], path: Path):
    keys = list(dict.fromkeys(k for r in rows for k in r))
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=keys, lineterminator="\n")
        w.writeheader()
        for r in rows:
            w.writerow({k: (f"{v:.1f}" if isinstance(v, float) else v) for k, v in r.items()})


def summarize(rows: list[dict]) -> list[dict]:
    nominal = [r for r in rows if r["covers"] == "nominais"]
    heavy = {(r["thigh_mm"], r["shin_mm"], r["hip_spacing_mm"]): r for r in rows if r["covers"] == "pesadas"}

    print("Por largura do quadril (capas nominais; faixa sobre todas as coxas/canelas):")
    print("  quadris  inclinação  deslocar peso 0,5/s  deslocar peso 1/s  passam 0,5/s  passam 1/s")
    for sp in sorted({r["hip_spacing_mm"] for r in nominal}):
        g = [r for r in nominal if r["hip_spacing_mm"] == sp]
        tilts = [r["tilt_needed_deg"] for r in g if not np.isnan(r["tilt_needed_deg"])]
        s05 = [r["shift05_pct"] for r in g if not np.isnan(r["shift05_pct"])]
        s10 = [r["shift10_pct"] for r in g if not np.isnan(r["shift10_pct"])]
        print(f"   {sp} mm    {min(tilts):3.0f}–{max(tilts):2.0f}°        {min(s05):3.0f}–{max(s05):3.0f}%"
              f"           {min(s10):3.0f}–{max(s10):3.0f}%       {sum(r['pass_05'] for r in g):2d}/{len(g)}"
              f"        {sum(r['pass_10'] for r in g):2d}/{len(g)}")

    def robust(r):
        h = heavy.get((r["thigh_mm"], r["shin_mm"], r["hip_spacing_mm"]))
        return h is None or h["pass_05"]

    ranked = sorted((r for r in nominal if r["pass_05"] and robust(r)),
                    key=lambda r: (not r["pass_10"], r["worst_pct_at_1step"]))
    print("\nMelhores combinações (passam a 0,5 passo/s também com capas pesadas; ordem: passa a 1 passo/s, menor pior pico):")
    print("  coxa  canela  quadris  massa  inclinação  levantar  apoio  deslocar 0,5/s  deslocar 1/s  1 passo/s?")
    for r in ranked[:12]:
        print(f"  {r['thigh_mm']:4d}  {r['shin_mm']:5d}   {r['hip_spacing_mm']:4d}    {r['mass_g']:4d}g    {r['tilt_needed_deg']:3.0f}°"
              f"      {r['rise_knee_pct']:4.0f}%   {r['stance_worst_pct']:4.0f}%       {r['shift05_pct']:4.0f}%"
              f"         {r['shift10_pct']:4.0f}%       {'sim' if r['pass_10'] else 'não'}")
    if not ranked:
        print("  nenhuma")
    return ranked


def plot(rows: list[dict], path: Path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    nominal = [r for r in rows if r["covers"] == "nominais"]
    spacings = sorted({r["hip_spacing_mm"] for r in nominal})
    thighs = sorted({r["thigh_mm"] for r in nominal})
    shins = sorted({r["shin_mm"] for r in nominal})
    fig, axes = plt.subplots(1, len(spacings) + 1, figsize=(3.8 * (len(spacings) + 1), 4.2))
    im = None
    for ax, sp in zip(axes, spacings):
        grid = np.full((len(shins), len(thighs)), np.nan)
        for r in nominal:
            if r["hip_spacing_mm"] == sp:
                grid[shins.index(r["shin_mm"]), thighs.index(r["thigh_mm"])] = r["worst_pct_at_1step"]
        step = (thighs[1] - thighs[0]) / 2 if len(thighs) > 1 else 2.5
        im = ax.imshow(grid, origin="lower", cmap="RdYlGn_r", vmin=30, vmax=100, aspect="auto",
                       extent=(thighs[0] - step, thighs[-1] + step, shins[0] - step, shins[-1] + step))
        for r in nominal:
            if r["hip_spacing_mm"] == sp:
                mark = "✓" if r["pass_10"] else ("½" if r["pass_05"] else "✗")
                ax.text(r["thigh_mm"], r["shin_mm"], mark, ha="center", va="center", fontsize=9)
        ax.set_title(f"quadris a {sp} mm")
        ax.set_xlabel("coxa (mm)")
        ax.set_ylabel("canela (mm)")
    fig.colorbar(im, ax=axes[:-1], label="pior pico a 1 passo/s (% do SG90)", shrink=0.8)
    ax = axes[-1]
    sums = sorted({r["thigh_mm"] + r["shin_mm"] for r in nominal})
    for sp in spacings:
        tilts = [np.nanmean([r["tilt_needed_deg"] for r in nominal
                             if r["hip_spacing_mm"] == sp and r["thigh_mm"] + r["shin_mm"] == s]) for s in sums]
        ax.plot(sums, tilts, marker="o", label=f"{sp} mm")
    ax.axhline(TILT_LIMIT, color="red", ls="--", lw=1)
    ax.set_title("inclinação para ficar numa perna")
    ax.set_xlabel("coxa + canela (mm)")
    ax.set_ylabel("graus")
    ax.legend(title="quadris", fontsize=8)
    fig.suptitle("F2 — ✓ passa a 1 passo/s   ½ só a 0,5 passo/s   ✗ não passa   (capas nominais)")
    fig.savefig(path, dpi=90, bbox_inches="tight")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--quick", action="store_true")
    args = ap.parse_args()
    RESULTS.mkdir(exist_ok=True)
    rows = run_grid(QUICK if args.quick else GRID)
    suffix = "_quick" if args.quick else ""
    save_csv(rows, RESULTS / f"f2_sweep{suffix}.csv")
    summarize(rows)
    plot(rows, RESULTS / f"f2_sweep{suffix}.png")
    print(f"\nresultados: sim/results/f2_sweep{suffix}.csv e .png")


if __name__ == "__main__":
    main()
